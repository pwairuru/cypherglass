#!/usr/bin/env python3
"""Generate typed chart specs from the YAML catalog.

Inputs:  docs/charts/chart-catalog.yaml
Outputs:
  frontend/src/charts/generated/catalog.ts
  backend-rs/src/charts/catalog.json

Usage:
  python3 scripts/generate_chart_catalog.py
  python3 scripts/generate_chart_catalog.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "docs/charts/chart-catalog.yaml"
TS_OUT = ROOT / "frontend/src/charts/generated/catalog.ts"
JSON_OUT = ROOT / "backend-rs/src/charts/catalog.json"

CHART_KEYS = {
    "id": "id",
    "title": "title",
    "category": "category",
    "status": "status",
    "implementation": "implementation",
    "phase": "phase",
    "priority": "priority",
    "question": "question",
    "parity": "parity",
    "archetype": "archetype",
    "chart_types": "chartTypes",
    "panes": "panes",
    "axes": "axes",
    "metrics": "metrics",
    "legacy_metrics": "legacyMetrics",
    "disabled_metrics": "disabledMetrics",
    "new_metrics": "newMetrics",
    "default_metric": "defaultMetric",
    "series": "series",
    "variants": "variants",
    "controls": "controls",
    "annotations": "annotations",
    "expected": "expected",
    "acceptance": "acceptance",
    "data_freshness": "dataFreshness",
    "data_requirements": "dataRequirements",
}

SERIES_KEYS = {
    "type": "type",
    "open": "open",
    "high": "high",
    "low": "low",
    "close": "close",
    "volume": "volume",
    "metric": "metric",
    "label": "label",
    "axis": "axis",
    "style": "style",
    "color": "color",
    "width": "width",
    "dash": "dash",
    "hidden_by_default": "hiddenByDefault",
    "transform": "transform",
}

VARIANT_KEYS = {
    "id": "id",
    "label": "label",
    "series": "series",
    "cohort": "cohort",
    "unit": "unit",
    "note": "note",
}

AXIS_KEYS = {
    "id": "id",
    "unit": "unit",
    "scale": "scale",
    "min": "min",
    "max": "max",
    "decimals": "decimals",
    "color": "color",
    "title": "title",
}


def normalise(mapping: dict, keys: dict[str, str]) -> dict:
    out = {}
    for src, dest in keys.items():
        if src in mapping:
            out[dest] = mapping[src]
    return out


def normalise_chart(chart: dict) -> dict:
    out = normalise(chart, CHART_KEYS)
    out["axes"] = [normalise(a, AXIS_KEYS) for a in chart.get("axes") or []]
    out["series"] = [normalise(s, SERIES_KEYS) for s in chart.get("series") or []]
    for series in out["series"]:
        series.setdefault("axis", "left")
        if series.get("type") == "ohlc":
            series.setdefault("style", "candle")
    out["variants"] = [normalise(v, VARIANT_KEYS) for v in chart.get("variants") or []]
    # Stable defaults keep the TS type total.
    for key in (
        "parity",
        "panes",
        "metrics",
        "legacyMetrics",
        "disabledMetrics",
        "newMetrics",
        "series",
        "variants",
        "controls",
        "annotations",
        "expected",
        "acceptance",
    ):
        out.setdefault(key, [])
    for key in ("chartTypes", "axes"):
        out.setdefault(key, [])
    out.setdefault("implementation", "not_started")
    out.setdefault("defaultMetric", None)
    out.setdefault("dataFreshness", "unknown")
    return out


def load() -> dict:
    raw = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))
    charts = [normalise_chart(c) for c in raw.get("charts") or []]
    return {
        "version": raw.get("version", 1),
        "generated": raw.get("generated"),
        "target": raw.get("target"),
        "counts": {
            "charts": len(charts),
            "existingCharts": sum(1 for c in charts if c["status"] == "existing"),
            "newCharts": sum(1 for c in charts if c["status"] == "new"),
            "metrics": (raw.get("counts") or {}).get("metrics", 0),
        },
        "archetypes": raw.get("archetypes") or {},
        "charts": charts,
    }


def render_ts(catalog: dict) -> str:
    payload = json.dumps(catalog["charts"], ensure_ascii=True, separators=(",", ":"))
    header = (
        "/* Generated by scripts/generate_chart_catalog.py — do not edit.\n"
        " * Source: docs/charts/chart-catalog.yaml\n"
        " */\n"
        'import type { ChartSpec } from "../types";\n\n'
        f"export const CATALOG_VERSION = {catalog['version']};\n"
        f"export const CATALOG: ChartSpec[] = {payload};\n"
    )
    return header


def render_json(catalog: dict) -> str:
    return json.dumps(catalog, ensure_ascii=False, indent=1) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    catalog = load()
    ts = render_ts(catalog)
    js = render_json(catalog)

    if args.check:
        problems = []
        if not TS_OUT.exists() or TS_OUT.read_text(encoding="utf-8") != ts:
            problems.append(str(TS_OUT.relative_to(ROOT)))
        if not JSON_OUT.exists() or JSON_OUT.read_text(encoding="utf-8") != js:
            problems.append(str(JSON_OUT.relative_to(ROOT)))
        if problems:
            print(
                "chart catalog generated files are out of date: "
                + ", ".join(problems)
                + "; run python3 scripts/generate_chart_catalog.py",
                file=sys.stderr,
            )
            return 1
        print(
            f"chart catalog OK: {catalog['counts']['charts']} charts, "
            f"{catalog['counts']['metrics']} metrics"
        )
        return 0

    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
    TS_OUT.write_text(ts, encoding="utf-8")
    JSON_OUT.write_text(js, encoding="utf-8")
    print(
        f"wrote {TS_OUT.relative_to(ROOT)} and {JSON_OUT.relative_to(ROOT)} "
        f"({catalog['counts']['charts']} charts)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
